import uuid
from datetime import date, datetime
from enum import StrEnum
from typing import Any

from sqlalchemy import (
    Date,
    DateTime,
    Enum,
    Float,
    ForeignKey,
    Index,
    String,
    Text,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.ext.asyncio import AsyncAttrs, async_sessionmaker, create_async_engine
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship

from app.core.config import get_settings


class Base(AsyncAttrs, DeclarativeBase):
    pass


class PhotoRole(StrEnum):
    BASELINE = "baseline"
    GOAL = "goal"
    PROGRESS = "progress"


class UserProfile(Base):
    __tablename__ = "user_profiles"

    user_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True)
    goal_summary: Mapped[str] = mapped_column(
        Text, default="Build lean muscle and reduce body fat"
    )
    preferred_style: Mapped[str] = mapped_column(String(100), default="hypertrophy")
    available_equipment: Mapped[list[str]] = mapped_column(JSONB, default=list)
    injuries_or_constraints: Mapped[str | None] = mapped_column(Text, nullable=True)
    days_per_week: Mapped[int] = mapped_column(default=4)

    baseline_photo_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("physique_photos.id", ondelete="SET NULL", use_alter=True),
        nullable=True,
    )
    goal_photo_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("physique_photos.id", ondelete="SET NULL", use_alter=True),
        nullable=True,
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )

    photos: Mapped[list["PhysiquePhoto"]] = relationship(
        back_populates="user",
        foreign_keys="PhysiquePhoto.user_id",
        cascade="all, delete-orphan",
    )
    workout_plans: Mapped[list["DailyWorkoutPlan"]] = relationship(
        back_populates="user", cascade="all, delete-orphan"
    )


class PhysiquePhoto(Base):
    __tablename__ = "physique_photos"
    __table_args__ = (
        Index("ix_physique_photos_user_created", "user_id", "created_at"),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("user_profiles.user_id", ondelete="CASCADE"),
        nullable=False,
    )
    role: Mapped[PhotoRole] = mapped_column(
        Enum(PhotoRole, name="photo_role_enum"), nullable=False
    )

    # Private S3/R2 object keys (raw and MediaPipe pose-aligned normalized image)
    raw_storage_key: Mapped[str] = mapped_column(String(512), nullable=False)
    aligned_storage_key: Mapped[str | None] = mapped_column(String(512), nullable=True)

    # Optional user metrics logged alongside photo
    weight_kg: Mapped[float | None] = mapped_column(Float, nullable=True)
    user_notes: Mapped[str | None] = mapped_column(Text, nullable=True)

    # Deterministic Computer Vision metrics (MediaPipe)
    shoulder_to_waist_ratio: Mapped[float | None] = mapped_column(Float, nullable=True)
    waist_to_hip_ratio: Mapped[float | None] = mapped_column(Float, nullable=True)
    pose_landmarks: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True)

    # Structured PydanticAI VLM comparison output
    ai_analysis: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )

    user: Mapped["UserProfile"] = relationship(
        back_populates="photos",
        foreign_keys=[user_id],
    )


class DailyWorkoutPlan(Base):
    __tablename__ = "daily_workout_plans"
    __table_args__ = (Index("ix_daily_workout_user_date", "user_id", "plan_date"),)

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("user_profiles.user_id", ondelete="CASCADE"),
        nullable=False,
    )
    plan_date: Mapped[date] = mapped_column(Date, nullable=False)
    focus_area: Mapped[str] = mapped_column(String(120), nullable=False)
    rationale: Mapped[str] = mapped_column(Text, nullable=False)

    # Structured list of workout tasks generated by PydanticAI
    tasks: Mapped[list[dict[str, Any]]] = mapped_column(JSONB, nullable=False)
    completed: Mapped[bool] = mapped_column(default=False)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )

    user: Mapped["UserProfile"] = relationship(back_populates="workout_plans")


def create_engine_and_sessionmaker() -> tuple[Any, async_sessionmaker[Any]]:
    settings = get_settings()
    engine = create_async_engine(
        settings.database_url.get_secret_value(),
        pool_pre_ping=True,
        pool_size=10,
        max_overflow=20,
    )
    session_factory = async_sessionmaker(engine, expire_on_commit=False)
    return engine, session_factory
